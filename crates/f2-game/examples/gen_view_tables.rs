//! Regenerates `crates/f2-game/src/view_tables.rs` (phase 3S): `InitMaths`' `sinFast` /
//! `acosFast` tables (mdxMath.cpp:53) as static bit patterns, so the simulation needs no
//! lazily initialised (atomic) table. The unit test in `view.rs` recomputes every entry.
//!
//! `cargo run -p f2-game --example gen_view_tables > crates/f2-game/src/view_tables.rs`

fn main() {
    const PI2: f64 = core::f64::consts::PI * 2.0;
    let sin: Vec<u32> = (0..4096).map(|i| (f2_math::detfloat::sin((i as f64 * PI2) / 4096.0) as f32).to_bits()).collect();
    let acos: Vec<u32> = (0..4096).map(|i| (f2_math::detfloat::acos((i as f64 - 2048.0) / 2048.0) as f32).to_bits()).collect();
    println!("//! Generated by `cargo run -p f2-game --example gen_view_tables` (phase 3S); do not edit.");
    println!("//! `InitMaths` (mdxMath.cpp:53) tables as `f32` bit patterns: `SIN[i]` = sin(i·2π/4096),");
    println!("//! `ACOS[i]` = acos((i − 2048)/2048), each evaluated in `f64` (detfloat) and rounded once.");
    println!();
    for (name, t) in [("SIN_BITS", &sin), ("ACOS_BITS", &acos)] {
        println!("pub(crate) static {name}: [u32; 4096] = [");
        for row in t.chunks(8) {
            let items: Vec<String> = row.iter().map(|v| format!("0x{v:08x}")).collect();
            println!("    {},", items.join(", "));
        }
        println!("];");
        println!();
    }
}
