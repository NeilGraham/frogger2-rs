//! Regenerates `src/tables.rs` (phase 3S): exact lookup tables of the float-backed PC
//! helpers, taken from their reference implementations (`rsin_float`, `arccos_float`).
//!
//! `cargo run -p f2-math --example gen_tables > crates/f2-math/src/tables.rs`
//!
//! The unit tests in `util.rs` / `maths.rs` check every table entry against the reference
//! again, so a stale table cannot go unnoticed.

use f2_math::{arccos_float, rsin_float};
use std::fmt::Write;

fn table(out: &mut String, name: &str, ty: &str, vals: &[i32]) {
    writeln!(out, "pub(crate) static {name}: [{ty}; {}] = [", vals.len()).unwrap();
    for row in vals.chunks(16) {
        let items: Vec<String> = row.iter().map(|v| v.to_string()).collect();
        writeln!(out, "    {},", items.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();
}

fn main() {
    let mut out = String::new();
    out.push_str(
        "//! Generated by `cargo run -p f2-math --example gen_tables` (phase 3S); do not edit.\n\
         //!\n\
         //! Exact outputs of the float-backed PC helpers over the domains where a lookup is\n\
         //! valid (checked exhaustively by the unit tests):\n\
         //! - `SIN_HALF[i]` = `rsin_float(i)` for `i` in `0..2048`; `rsin_float(i + 2048)` is\n\
         //!   `-SIN_HALF[i]` and both `rsin`/`rcos` are 4096-periodic for |x| < 10684.\n\
         //! - `ACOS[c + 4096]` = `arccos_float(c)` for `c` in `-4096..=4096`.\n\n",
    );
    let sin: Vec<i32> = (0..2048).map(rsin_float).collect();
    table(&mut out, "SIN_HALF", "i16", &sin);
    out.push('\n');
    let acos: Vec<i32> = (-4096..=4096).map(arccos_float).collect();
    table(&mut out, "ACOS", "u16", &acos);
    print!("{out}");
}
